const a = new Uint32Array(1)

/* unbiased crypto random index */
function rand(n) {
  const limit = Math.floor(0x100000000 / n) * n
  let v = 0
  do {
    crypto.getRandomValues(a)
    v = a[0]
  } while (v >= limit)
  return v % n
}

/* deterministic PRNG for the daily challenge */
export function mulberry32(seed) {
  let s = seed >>> 0
  return function () {
    s |= 0
    s = (s + 0x6d2b79f5) | 0
    let t = Math.imul(s ^ (s >>> 15), 1 | s)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

function sampleFrom(pool, n, drawIndex) {
  const out = []
  const recent = []
  /* pools small enough to saturate the recent-window can't reject repeats */
  const skipRecent = pool.length > 15
  while (out.length < n) {
    const w = pool[drawIndex(pool.length)]
    if (skipRecent && recent.includes(w)) continue
    out.push(w)
    recent.push(w)
    if (recent.length > 14) recent.shift()
  }
  return out
}

/* the head of the list is the everyday core, ordered roughly by how common
   each word is; "rare" is the long, uncommon tail */
export const COMMON_SIZE = 300
export const RARE_MIN_LEN = 7

function poolFor({ min = 0, max = Infinity, pool = "all" } = {}) {
  let list = WORDS
  if (pool === "common") list = WORDS.slice(0, COMMON_SIZE)
  else if (pool === "rare")
    list = WORDS.slice(COMMON_SIZE).filter((w) => w.length >= RARE_MIN_LEN)
  return min > 0 || max < Infinity
    ? list.filter((w) => w.length >= min && w.length <= max)
    : list
}

export function sampleWords(n, opts = {}) {
  return sampleFrom(poolFor(opts), n, (len) => rand(len))
}

export function sampleWordsSeeded(n, seed, { min = 0, max = Infinity } = {}) {
  const pool =
    min > 0 || max < Infinity
      ? WORDS.filter((w) => w.length >= min && w.length <= max)
      : WORDS
  const rng = mulberry32(seed)
  return sampleFrom(pool, n, (len) => Math.floor(rng() * len))
}
