const a = new Uint32Array(1)

/* unbiased crypto random index (matches words.js) */
function rand(n) {
  const limit = Math.floor(0x100000000 / n) * n
  let v = 0
  do {
    crypto.getRandomValues(a)
    v = a[0]
  } while (v >= limit)
  return v % n
}

export function sampleQuote() {
  return QUOTES[rand(QUOTES.length)]
}
